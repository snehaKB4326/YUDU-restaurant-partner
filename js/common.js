const STORAGE_KEY = 'yudu_partner_registration';

/**
 * Default Initial State
 */
const defaultRegistrationState = {
  step1: {
    restaurantName: '',
    ownerName: '',
    mobileNumber: '',
    businessEmail: '',
    cuisines: [],
    address: '',
    city: 'Hyderabad',
    pincode: '',
    opensAt: '10:00 AM',
    closesAt: '11:00 PM',
    isCompleted: false
  },
  step2: {
    documents: {
      fssai: null,       // { name, size, type, dataUrl, uploadedAt }
      gst: null,
      pan: null,
      cheque: null
    },
    photos: [],          // array of { id, name, size, dataUrl }
    isCompleted: false
  },
  step3: {
    isConfirmed: false,
    submittedAt: null,
    applicationRef: null,
    status: 'Pending Verification'
  }
};

/**
 * Retrieve state from localStorage
 */
function getYuduData() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return JSON.parse(JSON.stringify(defaultRegistrationState));
    const parsed = JSON.parse(raw);
    return {
      step1: { ...defaultRegistrationState.step1, ...(parsed.step1 || {}) },
      step2: { 
        ...defaultRegistrationState.step2, 
        ...(parsed.step2 || {}),
        documents: { ...defaultRegistrationState.step2.documents, ...(parsed.step2?.documents || {}) },
        photos: parsed.step2?.photos || []
      },
      step3: { ...defaultRegistrationState.step3, ...(parsed.step3 || {}) }
    };
  } catch (e) {
    console.error('Error reading localStorage data', e);
    return JSON.parse(JSON.stringify(defaultRegistrationState));
  }
}

/**
 * Persist state to localStorage
 */
function saveYuduData(data) {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(data));
  } catch (e) {
    console.error('Error saving data to localStorage', e);
    showToast('Storage Warning', 'Local storage quota exceeded or unavailable.', 'error');
  }
}

/**
 * Update partial step data
 */
function updateYuduStepData(stepKey, stepData) {
  const current = getYuduData();
  current[stepKey] = {
    ...current[stepKey],
    ...stepData
  };
  saveYuduData(current);
  return current;
}

/**
 * Reset all registration state
 */
function clearYuduData() {
  localStorage.removeItem(STORAGE_KEY);
}

/**
 * Toast Notification System
 */
function showToast(title, message, type = 'info', duration = 3500) {
  let container = document.querySelector('.toast-container');
  if (!container) {
    container = document.createElement('div');
    container.className = 'toast-container';
    document.body.appendChild(container);
  }

  const toast = document.createElement('div');
  toast.className = `toast toast-${type}`;
  
  let iconHtml = '✨';
  if (type === 'success') iconHtml = '✓';
  if (type === 'error') iconHtml = '⚠';

  toast.innerHTML = `
    <div class="toast-icon" style="font-weight: bold; color: ${type === 'success' ? '#168B4B' : (type === 'error' ? '#E5484D' : '#5420A8')}; font-size: 1.1rem;">
      ${iconHtml}
    </div>
    <div class="toast-content">
      <div class="toast-title">${title}</div>
      <div class="toast-message">${message}</div>
    </div>
    <button class="toast-close" aria-label="Close">&times;</button>
  `;

  container.appendChild(toast);

  // Trigger animation
  requestAnimationFrame(() => {
    toast.classList.add('show');
  });

  const closeToast = () => {
    toast.classList.remove('show');
    setTimeout(() => {
      if (toast.parentElement) toast.parentElement.removeChild(toast);
    }, 300);
  };

  toast.querySelector('.toast-close').addEventListener('click', closeToast);

  if (duration > 0) {
    setTimeout(closeToast, duration);
  }
}

/**
 * Validation Helpers
 */
function isValidEmail(email) {
  const re = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
  return re.test(String(email).trim().toLowerCase());
}

function isValidMobile(mobile) {
  // Accepts 10 digits or with optional +91 prefix / spaces
  const cleaned = String(mobile).replace(/\D/g, '');
  return cleaned.length === 10 || (cleaned.length === 12 && cleaned.startsWith('91'));
}

function isValidPincode(pincode) {
  // 6 digits Indian pincode
  return /^\d{6}$/.test(String(pincode).trim());
}

/**
 * Format bytes to human readable string
 */
function formatBytes(bytes, decimals = 1) {
  if (!bytes || bytes === 0) return '0 B';
  const k = 1024;
  const dm = decimals < 0 ? 0 : decimals;
  const sizes = ['B', 'KB', 'MB', 'GB'];
  const i = Math.floor(Math.log(bytes) / Math.log(k));
  return parseFloat((bytes / Math.pow(k, i)).toFixed(dm)) + ' ' + sizes[i];
}

