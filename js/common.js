/**
 * Initialize Lucide icons with inline SVG fallback
 */
function refreshIcons() {
  if (window.lucide && typeof window.lucide.createIcons === 'function') {
    try {
      window.lucide.createIcons();
    } catch (e) {
      console.warn('Lucide createIcons failed, applying fallback icons', e);
    }
  }

  // Fallback for any un-rendered [data-lucide]
  document.querySelectorAll('[data-lucide]').forEach(el => {
    if (!el.hasChildNodes() || el.tagName.toLowerCase() === 'i') {
      const iconName = el.getAttribute('data-lucide');
      if (SVG_ICONS[iconName]) {
        el.innerHTML = SVG_ICONS[iconName];
      }
    }
  });
}

document.addEventListener('DOMContentLoaded', () => {
  refreshIcons();
});
